package Web_Drink_Store.webstore.enums;

/**
 * Ice level options.
 * Mapping theo DEFAULT_ICE trong ProductDetailPage.jsx:
 * ['Nóng', 'Ít đá (30%)', 'Đá vừa (70%)', 'Đầy đá (100%)']
 */
public enum DrinkIce {
    HOT,        // Nóng
    LESS_ICE,   // Ít đá (30%)
    NORMAL_ICE, // Đá vừa (70%)
    FULL_ICE    // Đầy đá (100%)
}
